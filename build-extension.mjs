// Copies the shared library files the browser extension needs into
// extension/vendor/, so `Load unpacked → extension/` gets a self-contained
// directory. Run `npm run bundle-libs` first (the build script chains it) so the
// bundles exist.
//
// These are copies rather than symlinks on purpose: Chrome packs the extension
// directory as-is, and a symlink pointing outside it would not survive.
// extension/vendor/ is gitignored — the sources of truth stay at the repo root
// alongside the site's own copies.

import * as fs from 'node:fs/promises';
import * as path from 'node:path';

const root = import.meta.dirname;
const vendorDir = path.join(root, 'extension', 'vendor');

// The codec (used by the service worker) and Readability (used by the content
// script). The UI bundles are not needed — the extension renders its own popup.
const files = [
	'linkify.ink.js',
	'vendor.codec.bundle.js',
	'vendor.readability.bundle.js',
];

await fs.rm(vendorDir, { recursive: true, force: true });
await fs.mkdir(vendorDir, { recursive: true });

for (const file of files) {
	await fs.copyFile(path.join(root, file), path.join(vendorDir, file));
}

// The codec bundle is `@ts-nocheck`'d generated JS, so without a sibling .d.ts
// `npm run typecheck` sees the service worker's import as `any`-ish and the
// LinkifyInk constructor call stops being checked. The root .d.ts can't just be
// copied — it re-exports './vendor.codec.js', whose own './node_modules/...'
// imports only resolve from the repo root — so point it back there instead.
// Chrome never loads .d.ts files; this exists purely for the type checker.
await fs.writeFile(
	path.join(vendorDir, 'vendor.codec.bundle.d.ts'),
	"// Generated by build-extension.mjs — do not edit.\nexport * from '../../vendor.codec.js';\n",
);

console.log(`Copied ${files.length} files into extension/vendor/.`);

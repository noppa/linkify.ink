// Assembles the browser extension for each target browser.
//
// extension/ is the shared source tree. This script (1) copies the shared library
// files into extension/vendor/, then (2) writes one self-contained directory per
// browser to dist/extension/<browser>/: the shared files plus a manifest.json
// merged from extension/manifests/base.json and <browser>.json. Run `npm run bundle-libs` first (the build script chains it) so the
// bundles exist.
//
// These are copies rather than symlinks on purpose: browsers pack the extension
// directory as-is, and a symlink pointing outside it would not survive.
// extension/vendor/ is gitignored — the sources of truth stay in the repo
// (linkify.ink.js at the root, the bundles in vendor/).

import * as fs from 'node:fs/promises';
import * as path from 'node:path';

const root = import.meta.dirname;
const extensionDir = path.join(root, 'extension');
const vendorDir = path.join(extensionDir, 'vendor');
const distDir = path.join(root, 'dist', 'extension');

/** Browsers to build for; each needs extension/manifests/<name>.json. */
const targets = ['chrome', 'firefox'];

/** Source-tree files that don't ship in the built extension. */
const notShipped = new Set(['manifests', 'README.md', 'types.d.ts']);

// The codec (used by the service worker) and Readability (used by the content
// script). The UI bundles are not needed — the extension renders its own popup.
const files = [
	'linkify.ink.js',
	'vendor/vendor.codec.bundle.js',
	'vendor/vendor.readability.bundle.js',
];

await fs.rm(vendorDir, { recursive: true, force: true });
await fs.mkdir(vendorDir, { recursive: true });

for (const file of files) {
	await fs.copyFile(path.join(root, file), path.join(vendorDir, path.basename(file)));
}

// The codec bundle is `@ts-nocheck`'d generated JS, so without a sibling .d.ts
// `npm run typecheck` sees the service worker's import as `any`-ish and the
// LinkifyInk constructor call stops being checked. The root .d.ts can't just be
// copied — it re-exports './vendor.codec.js', whose own '../node_modules/...'
// imports only resolve from the repo root — so point it back there instead.
// Browsers never load .d.ts files; this exists purely for the type checker.
await fs.writeFile(
	path.join(vendorDir, 'vendor.codec.bundle.d.ts'),
	"// Generated by build-extension.mjs — do not edit.\nexport * from '../../vendor/vendor.codec.js';\n",
);

console.log(`Copied ${files.length} files into extension/vendor/.`);

/** @param {string} file */
async function readJson(file) {
	return JSON.parse(await fs.readFile(file, 'utf8'));
}

const base = await readJson(path.join(extensionDir, 'manifests', 'base.json'));

await fs.rm(distDir, { recursive: true, force: true });

for (const target of targets) {
	const outDir = path.join(distDir, target);
	await fs.cp(extensionDir, outDir, {
		recursive: true,
		filter: (src) => {
			const rel = path.relative(extensionDir, src);
			return !notShipped.has(rel.split(path.sep)[0]) && !rel.endsWith('.d.ts');
		},
	});

	// Shallow merge: a target's keys replace the base's, which is all the
	// differences between browsers need (background, browser_specific_settings).
	const overrides = await readJson(path.join(extensionDir, 'manifests', `${target}.json`));
	const manifest = { ...base, ...overrides };
	await fs.writeFile(path.join(outDir, 'manifest.json'), JSON.stringify(manifest, null, '\t') + '\n');
	console.log(`Built dist/extension/${target}/`);
}
